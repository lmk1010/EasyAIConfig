  function hasHan(text) {
    return /[\u3400-\u9fff]/.test(String(text || ''));
  }

  function normalize(text) {
    return String(text == null ? '' : text).replace(/\s+/g, ' ').trim();
  }

  function preserveOuterWhitespace(source, translated) {
    const raw = String(source == null ? '' : source);
    const lead = raw.match(/^\s*/)?.[0] || '';
    const trail = raw.match(/\s*$/)?.[0] || '';
    return `${lead}${translated}${trail}`;
  }

  function translateCore(text) {
    const source = String(text == null ? '' : text);
    if (!source || !hasHan(source)) return source;
    const compact = normalize(source);
    if (!compact) return source;
    if (exactEn[compact]) return preserveOuterWhitespace(source, exactEn[compact]);
    for (const [re, fn] of patternEn) {
      const match = compact.match(re);
      if (match) return preserveOuterWhitespace(source, fn(match));
    }
    let out = compact;
    for (const key of phraseKeys) {
      if (out.includes(key)) out = out.split(key).join(phrasesEn[key]);
    }
    out = out
      .replace(/（/g, ' (')
      .replace(/）/g, ')')
      .replace(/，/g, ', ')
      .replace(/。/g, '.')
      .replace(/；/g, '; ')
      .replace(/：/g, ': ')
      .replace(/、/g, ', ')
      .replace(/“|”/g, '"')
      .replace(/「|」/g, '"')
      .replace(/？/g, '?')
      .replace(/！/g, '!')
      .replace(/\s{2,}/g, ' ')
      .trim();
    return preserveOuterWhitespace(source, out);
  }

